#!/usr/bin/env node
// Precomputes the two-phase (Kociemba) solver's move and pruning tables that
// `Cube.initSolver()` otherwise builds from scratch via BFS/DFS every time a
// page loads — measured at ~2.5s and ~35MB of heap on a fast desktop CPU, so
// considerably worse on typical mobile hardware, and a strong suspect for
// mobile crashes on load (the worker computes this unconditionally just to
// produce the very first scramble). This script runs that same computation
// once, here, and writes the result as a single static binary asset
// (public/solver-tables.<version>.bin) that the app fetches at runtime and
// decodes in milliseconds instead of recomputing it every session.
//
// Deliberately NOT embedded as a base64 string in a JS module: that was the
// first version of this fix, and it made the cube-engine worker's own
// script balloon to 7MB+ (base64 inflates size ~33%, on top of everything
// else already in that bundle) — a single script that large is itself a
// plausible new failure mode on constrained mobile connections/devices,
// since a Worker can't do anything until its whole script downloads,
// parses, and compiles. A plain static asset fetched with `fetch()`
// sidesteps all of that: it's a normal, browser- and service-worker-
// cacheable HTTP resource, decoded directly from raw bytes (no base64
// overhead), and it doesn't bloat the worker script itself at all.
//
// `Cube.computeMoveTables()`/`computePruningTables()` (vendor/solve.js) both
// skip any table that's already non-null, so at runtime we just need to
// populate `Cube.moveTables`/`Cube.pruningTables` from this data *before*
// `Cube.initSolver()` runs — it then finds everything already there and
// returns instantly. Nothing about the solver's own logic changes.
"use strict";

const fs = require("fs");
const path = require("path");
const Cube = require("../src/lib/cube-engine/vendor/index.js");

// Bump this if the data is ever regenerated — public/ assets keep their
// exact filename (unlike hashed _next/static chunks), so a version in the
// name is what lets a change invalidate old caches instead of silently
// serving stale bytes forever.
const VERSION = "v1";

console.log("Computing solver tables (this takes a few seconds)...");
console.time("initSolver");
Cube.initSolver();
console.timeEnd("initSolver");

// Move tables: name -> rows x cols nested array of coordinate indices.
// Every table's values fit in Int16 range (max coordinate is 20160) except
// mergeURtoDF, which also uses -1 as a collision sentinel — Int16 covers
// that too, so one encoding serves every table uniformly.
const MOVE_TABLES = ["twist", "flip", "FRtoBR", "URFtoDLF", "URtoDF", "URtoUL", "UBtoDF", "mergeURtoDF"];
// Pruning tables: name -> flat array of 32-bit words, 8 packed 4-bit
// distances per word (see vendor/solve.js's `pruning()` helper).
const PRUNING_TABLES = ["sliceTwist", "sliceFlip", "sliceURFtoDLFParity", "sliceURtoDFParity"];

const buffers = [];
let offset = 0;
const manifestEntries = [];

for (const name of MOVE_TABLES) {
  const rows = Cube.moveTables[name];
  const numRows = rows.length;
  const numCols = rows[0].length;
  const flat = new Int16Array(numRows * numCols);
  for (let i = 0; i < numRows; i++) {
    const row = rows[i];
    for (let j = 0; j < numCols; j++) flat[i * numCols + j] = row[j];
  }
  const buf = Buffer.from(flat.buffer);
  buffers.push(buf);
  manifestEntries.push({ kind: "move", name, rows: numRows, cols: numCols, byteOffset: offset, byteLength: buf.length });
  offset += buf.length;
}

for (const name of PRUNING_TABLES) {
  const words = Cube.pruningTables[name];
  const flat = new Uint32Array(words.length);
  for (let i = 0; i < words.length; i++) flat[i] = words[i];
  const buf = Buffer.from(flat.buffer);
  buffers.push(buf);
  manifestEntries.push({ kind: "pruning", name, length: words.length, byteOffset: offset, byteLength: buf.length });
  offset += buf.length;
}

const combined = Buffer.concat(buffers);
const binOutPath = path.join(__dirname, "..", "public", `solver-tables.${VERSION}.bin`);
fs.writeFileSync(binOutPath, combined);
console.log(`Wrote ${binOutPath} (${(combined.length / 1024 / 1024).toFixed(2)} MB)`);

const manifestLines = [
  "// AUTO-GENERATED by scripts/gen-solver-tables.cjs. Do not edit by hand.",
  "//",
  "// Byte layout of public/solver-tables." + VERSION + ".bin — see that script",
  "// for why this data is a fetched static asset rather than embedded in a",
  "// JS module.",
  "",
  `export const SOLVER_TABLES_URL = "/solver-tables.${VERSION}.bin";`,
  "",
  "export interface MoveTableEntry {",
  "  name: string;",
  "  rows: number;",
  "  cols: number;",
  "  byteOffset: number;",
  "  byteLength: number;",
  "}",
  "",
  "export interface PruningTableEntry {",
  "  name: string;",
  "  length: number;",
  "  byteOffset: number;",
  "  byteLength: number;",
  "}",
  "",
  "export const MOVE_TABLE_MANIFEST: readonly MoveTableEntry[] = [",
];
for (const e of manifestEntries.filter((e) => e.kind === "move")) {
  manifestLines.push(
    `  { name: ${JSON.stringify(e.name)}, rows: ${e.rows}, cols: ${e.cols}, byteOffset: ${e.byteOffset}, byteLength: ${e.byteLength} },`,
  );
}
manifestLines.push("];", "");
manifestLines.push("export const PRUNING_TABLE_MANIFEST: readonly PruningTableEntry[] = [");
for (const e of manifestEntries.filter((e) => e.kind === "pruning")) {
  manifestLines.push(
    `  { name: ${JSON.stringify(e.name)}, length: ${e.length}, byteOffset: ${e.byteOffset}, byteLength: ${e.byteLength} },`,
  );
}
manifestLines.push("];", "");

const manifestOutPath = path.join(__dirname, "..", "src", "lib", "cube-engine", "data", "solverTablesManifest.generated.ts");
fs.mkdirSync(path.dirname(manifestOutPath), { recursive: true });
fs.writeFileSync(manifestOutPath, manifestLines.join("\n"));
console.log(`Wrote ${manifestOutPath}`);
