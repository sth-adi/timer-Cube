#!/usr/bin/env node
// Precomputes exact BFS distance tables for reduced piece subsets, used as
// admissible IDA* heuristics by the F2L and last-layer solvers. Same
// technique as gen-cross-table.cjs: BFS from solved using all 18 moves,
// hashing states only by the tracked pieces' (slot, orientation), which
// gives an exact distance for the *relaxed* problem (ignoring every other
// piece) -- a valid lower bound for any real, more-constrained search that
// also has to keep other pieces fixed.
"use strict";

const fs = require("fs");
const path = require("path");
const Cube = require("../src/lib/cube-engine/vendor/index.js");

// R, F, D, L, B — U excluded, matching the actual F2L/OLL/PLL solvers (which
// never turn U once the cross is solved — the cross lives on U/white, see
// cube-engine/engine.ts). Building these heuristic tables with the SAME
// move set the real search uses is what makes them tight.
const FACES = [1, 2, 3, 4, 5];

function buildTable({ name, kind, trackedIds, slotCount, oriCount }) {
  const size = Math.pow(slotCount, trackedIds.length) * Math.pow(oriCount, trackedIds.length);
  const dist = new Uint8Array(size).fill(255);

  const posArr = kind === "corner" ? "cp" : "ep";
  const oriArr = kind === "corner" ? "co" : "eo";

  function indexOf(cube) {
    let idx = 0;
    for (const id of trackedIds) idx = idx * slotCount + cube[posArr].indexOf(id);
    for (const id of trackedIds) {
      const slot = cube[posArr].indexOf(id);
      idx = idx * oriCount + cube[oriArr][slot];
    }
    return idx;
  }

  const start = new Cube();
  const startIdx = indexOf(start);
  dist[startIdx] = 0;

  let frontier = [start];
  let depth = 0;
  let visitedCount = 1;

  while (frontier.length > 0) {
    const next = [];
    for (const state of frontier) {
      for (const face of FACES) {
        for (let power = 0; power <= 2; power++) {
          const child = state.clone();
          for (let t = 0; t <= power; t++) child.multiply(Cube.moves[face]);
          const idx = indexOf(child);
          if (dist[idx] === 255) {
            dist[idx] = depth + 1;
            visitedCount++;
            next.push(child);
          }
        }
      }
    }
    frontier = next;
    depth++;
  }

  console.log(`[${name}] visited ${visitedCount}/${size} states, max depth ${depth - 1}`);
  return { dist, size };
}

const tables = [
  {
    name: "lastLayerCorners",
    kind: "corner",
    trackedIds: [4, 5, 6, 7], // DFR, DLF, DBL, DRB
    slotCount: 8,
    oriCount: 3,
  },
  {
    name: "lastLayerEdges",
    kind: "edge",
    trackedIds: [4, 5, 6, 7], // DR, DF, DL, DB
    slotCount: 12,
    oriCount: 2,
  },
  {
    name: "f2lPairFR",
    kind: "pair",
    corner: 0, // URF
    edge: 8, // FR
  },
  {
    name: "f2lPairFL",
    kind: "pair",
    corner: 1, // UFL
    edge: 9, // FL
  },
  {
    name: "f2lPairBL",
    kind: "pair",
    corner: 2, // ULB
    edge: 10, // BL
  },
  {
    name: "f2lPairBR",
    kind: "pair",
    corner: 3, // UBR
    edge: 11, // BR
  },
];

function buildPairTable({ name, corner, edge }) {
  // Tracks one corner (8 slots x 3 ori = 24) and one edge (12 slots x 2 ori = 24).
  const size = 8 * 3 * 12 * 2;
  const dist = new Uint8Array(size).fill(255);

  function indexOf(cube) {
    const cSlot = cube.cp.indexOf(corner);
    const cOri = cube.co[cSlot];
    const eSlot = cube.ep.indexOf(edge);
    const eOri = cube.eo[eSlot];
    return ((cSlot * 3 + cOri) * 12 + eSlot) * 2 + eOri;
  }

  const start = new Cube();
  dist[indexOf(start)] = 0;
  let frontier = [start];
  let depth = 0;
  let visitedCount = 1;

  while (frontier.length > 0) {
    const next = [];
    for (const state of frontier) {
      for (const face of FACES) {
        for (let power = 0; power <= 2; power++) {
          const child = state.clone();
          for (let t = 0; t <= power; t++) child.multiply(Cube.moves[face]);
          const idx = indexOf(child);
          if (dist[idx] === 255) {
            dist[idx] = depth + 1;
            visitedCount++;
            next.push(child);
          }
        }
      }
    }
    frontier = next;
    depth++;
  }

  console.log(`[${name}] visited ${visitedCount}/${size} states, max depth ${depth - 1}`);
  return { dist, size };
}

const results = {};
for (const t of tables) {
  results[t.name] = t.kind === "pair" ? buildPairTable(t) : buildTable(t);
}

const outPath = path.join(__dirname, "..", "src", "lib", "solvers", "data", "pieceTables.generated.ts");
let contents = `// AUTO-GENERATED by scripts/gen-piece-tables.cjs. Do not edit by hand.\n`;
for (const [name, { dist, size }] of Object.entries(results)) {
  const b64 = Buffer.from(dist.buffer).toString("base64");
  const constName = name.replace(/^[a-z]/, (c) => c.toUpperCase());
  contents += `export const ${constName}_SIZE = ${size};\n`;
  contents += `export const ${constName}_B64 =\n  "${b64}";\n`;
}
fs.writeFileSync(outPath, contents);
console.log(`Wrote ${outPath}`);
