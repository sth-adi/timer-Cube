#!/usr/bin/env node
// Precomputes an exact BFS distance table for the "cross" subgroup: the
// positions+orientations of the 4 cross edges (UR, UF, UL, UB in Kociemba
// edge numbering — the cross lives on U/white, see cube-engine/engine.ts),
// ignoring all corners and the other 8 edges. This table is exact (a full
// pruning table, not a heuristic), so solving from it is simply: look up
// the distance, then greedily walk to a neighbor with distance-1 until
// solved. That neighbor-walk is guaranteed optimal.
//
// Output: a base64-encoded Uint8Array (one byte per state index, 0-8, or
// 255 = never populated / not a reachable distinct-position-orientation
// combination) embedded as a TS module, so it ships as part of the JS
// bundle with no extra network fetch.
"use strict";

const fs = require("fs");
const path = require("path");
const Cube = require("../src/lib/cube-engine/vendor/index.js");

const CROSS_EDGES = [0, 1, 2, 3]; // UR, UF, UL, UB

function indexOf(cube) {
  // For each tracked edge id, find its current slot + orientation.
  let idx = 0;
  for (const edgeId of CROSS_EDGES) {
    const slot = cube.ep.indexOf(edgeId);
    idx = idx * 12 + slot;
  }
  for (const edgeId of CROSS_EDGES) {
    const slot = cube.ep.indexOf(edgeId);
    idx = idx * 2 + cube.eo[slot];
  }
  return idx;
}

const TABLE_SIZE = 12 * 12 * 12 * 12 * 2 * 2 * 2 * 2; // 331,776
const dist = new Uint8Array(TABLE_SIZE).fill(255);

const start = new Cube();
const startIdx = indexOf(start);
dist[startIdx] = 0;

let frontier = [start];
let depth = 0;
let visitedCount = 1;

while (frontier.length > 0) {
  const next = [];
  for (const state of frontier) {
    for (let face = 0; face <= 5; face++) {
      for (let power = 0; power <= 2; power++) {
        const child = state.clone();
        for (let t = 0; t <= power; t++) {
          child.multiply(Cube.moves[face]);
        }
        const idx = indexOf(child);
        if (dist[idx] === 255) {
          dist[idx] = depth + 1;
          visitedCount++;
          next.push(child);
        }
      }
    }
  }
  frontier = next;
  depth++;
}

console.log(`Visited ${visitedCount} distinct cross states, max depth ${depth - 1}`);

const b64 = Buffer.from(dist.buffer).toString("base64");
const outPath = path.join(__dirname, "..", "src", "lib", "solvers", "data", "crossTable.generated.ts");
const contents = `// AUTO-GENERATED by scripts/gen-cross-table.cjs. Do not edit by hand.
// Base64-encoded Uint8Array of length ${TABLE_SIZE}: exact BFS distance (0-8)
// from solved for every (position, orientation) combination of the 4 cross
// edges (UR, UF, UL, UB), or 255 if unused padding.
export const CROSS_TABLE_SIZE = ${TABLE_SIZE};
export const CROSS_TABLE_B64 =
  "${b64}";
`;
fs.writeFileSync(outPath, contents);
console.log(`Wrote ${outPath} (${(b64.length / 1024).toFixed(1)} KB base64)`);
